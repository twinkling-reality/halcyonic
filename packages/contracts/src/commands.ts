const strict = { additionalProperties: false } as const;

const CommandBase = {
  schema_version: Type.Literal(COMMAND_SCHEMA_VERSION),
  /** Generated by the client. Resubmitting the same command with the same id is idempotent. */
  command_id: CommandId,
  /** Client clock, recorded for audit. Ordering uses the journal, never this value. */
  issued_at: Timestamp,
  client: ClientInfo,
};

function defineCommand<const T extends string, P extends TSchema>(commandType: T, payload: P) {
  return Type.Object({ ...CommandBase, command_type: Type.Literal(commandType), payload }, strict);
}

export const ProjectCreateCommand = defineCommand(
  'project.create',
  Type.Object(
    {
      name: Text(200),
      /**
       * Where the project's files live on the host, or null for a project whose work needs no
       * folder, such as the mock runtime's. A runtime that uses the project's location refuses to
       * start work in a project without one.
       */
      location: Nullable(ProjectLocationChoice),
    },
    strict,
  ),
);

/**
 * Binds a project to another folder, for example after its folder was moved, or gives one to a
 * project created without. Executions already started keep the folder they started in.
 */
export const ProjectSetLocationCommand = defineCommand(
  'project.set_location',
  Type.Object({ project_id: ProjectId, location: ProjectLocationChoice }, strict),
);

/**
 * Puts every file of the project's folder back as one of its checkpoints holds it (ADR 0036). The
 * host does it, never a runtime, and completes it only once it has read every file again and found
 * it equal to the checkpoint.
 */
export const ProjectRestoreCommand = defineCommand(
  'project.restore',
  Type.Object({ project_id: ProjectId, checkpoint_id: CheckpointId }, strict),
);

/**
 * Checks a project made from a starter (ADR 0037): type check, build, and the built copy opened for
 * 10 seconds in the host's sandboxed headless browser. The host does it, never a runtime; it
 * completes once the findings are recorded, whatever they are.
 */
export const ProjectCheckCommand = defineCommand(
  'project.check',
  Type.Object({ project_id: ProjectId }, strict),
);

/**
 * Serves the built copy of the project's latest check on a loopback port, only when that check
 * passed. The live folder is never served, so nothing changed after the check reaches the page.
 */
export const ProjectPreviewStartCommand = defineCommand(
  'project.preview.start',
  Type.Object({ project_id: ProjectId }, strict),
);

/** Stops the project's preview. */
export const ProjectPreviewStopCommand = defineCommand(
  'project.preview.stop',
  Type.Object({ project_id: ProjectId }, strict),
);

/**
 * Links the project to one repository of the person's catalog (ADR 0039), replacing any link it
 * had. The person's own choice: the host may suggest a repository, never link one itself.
 */
export const ProjectLinkCatalogCommand = defineCommand(
  'project.link_catalog',
  Type.Object({ project_id: ProjectId, catalog: CatalogRepositoryRef }, strict),
);

/** Removes the project's link to its catalog repository. */
export const ProjectUnlinkCatalogCommand = defineCommand(
  'project.unlink_catalog',
  Type.Object({ project_id: ProjectId }, strict),
);

