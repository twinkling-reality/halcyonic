export const RejectionCode = Type.Union([
  Type.Literal('request_not_found'),
  Type.Literal('project_not_found'),
  Type.Literal('workstream_not_found'),
  Type.Literal('execution_not_found'),
  Type.Literal('runtime_not_found'),
  Type.Literal('approval_not_found'),
  /** An approve for a request that was never shown whole (`approvable` false): only deny is admitted. */
  Type.Literal('approval_not_whole'),
  /** The question is not, or no longer, waiting for an answer on this execution. */
  Type.Literal('question_not_found'),
  /** The answers do not fit the questions: one missing or repeated, or an unknown option. */
  Type.Literal('invalid_answer'),
  /** The runtime lists the models it can use, and the start chose none (`model_ref` is null). */
  Type.Literal('model_required'),
  Type.Literal('capability_unsupported'),
  Type.Literal('invalid_state'),
  Type.Literal('invalid_runtime_options'),
  /** The runtime works in the project's folder, and the project has none. */
  Type.Literal('location_required'),
  /** The folder, or the project root a new folder was to go in, is not there or is not a folder. */
  Type.Literal('location_missing'),
  /**
   * The folder lies outside every project root the host allows, also through `..` or a symbolic
   * link, or the host allows none.
   */
  Type.Literal('location_not_allowed'),
  /** Something already has the name a new folder was to get. */
  Type.Literal('location_exists'),
  /** The checkpoint is not one of this project's. */
  Type.Literal('checkpoint_not_found'),
  /**
   * The client is playing a recorded demonstration on its own device: the command was not sent to
   * any control plane or agent, however admissible it was in the recording. Only the client's
   * demonstration answers with it; a control plane never does.
   */
  Type.Literal('demonstration'),
  /**
   * The command came from a paired device the owner has revoked: over a connection or in a request
   * it opened before the revocation, as the credential is refused on every new one (ADR 0017).
   */
  Type.Literal('device_revoked'),
]);
export type RejectionCode = Static<typeof RejectionCode>;

export const CommandRejection = Type.Object({ code: RejectionCode, message: Text(2000) }, strict);
export type CommandRejection = Static<typeof CommandRejection>;

/**
 * Why an accepted command did not succeed. `effect` states whether the runtime may nevertheless
 * have acted: `unknown` after a timeout means the action may or may not have happened.
 */
export const CommandFailure = Type.Object(
  {
    code: Type.String({ pattern: '^[a-z][a-z0-9_]{0,63}$' }),
    message: Text(2000),
    effect: Type.Union([Type.Literal('none'), Type.Literal('unknown')]),
  },
  strict,
);
export type CommandFailure = Static<typeof CommandFailure>;

